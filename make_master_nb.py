                "# Cell 4: Log-Polar Fourier-Mellin Frequency Pre-alignment\n",
                "def estimate_fourier_mellin(img_ref, img_src):\n",
                "    g1 = img_ref.astype(np.float32)\n",
                "    g2 = img_src.astype(np.float32)\n",
                "    h, w = g1.shape\n",
                "    win = cv2.createHanningWindow((w, h), cv2.CV_32F)\n",
                "    f1 = np.fft.fftshift(np.fft.fft2(g1 * win))\n",
                "    f2 = np.fft.fftshift(np.fft.fft2(g2 * win))\n",
                "    mag1 = np.log(np.abs(f1) + 1.0)\n",
                "    mag2 = np.log(np.abs(f2) + 1.0)\n",
                "    center = (w / 2.0, h / 2.0)\n",
                "    max_radius = min(h, w) / 2.0\n",
                "    lp1 = cv2.warpPolar(mag1, (w, h), center, max_radius, cv2.WARP_POLAR_LOG + cv2.INTER_LINEAR)\n",
                "    lp2 = cv2.warpPolar(mag2, (w, h), center, max_radius, cv2.WARP_POLAR_LOG + cv2.INTER_LINEAR)\n",
